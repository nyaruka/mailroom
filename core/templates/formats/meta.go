package formats

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/nyaruka/mailroom/v26/core/templates"
)

var metaVariableRegex = regexp.MustCompile(`{{(\d+)}}`)

// MetaTemplate is a template in Meta's format, as returned by the Graph API and by providers which proxy it
type MetaTemplate struct {
	ID         externalID       `json:"id"`
	Name       string           `json:"name"`
	Language   string           `json:"language"`
	Status     string           `json:"status"`
	Namespace  *string          `json:"namespace"`
	Source     string           `json:"source"`
	Components []*MetaComponent `json:"components"`
}

// MetaPage is a page of templates from the Graph API
type MetaPage struct {
	Data   []*MetaTemplate `json:"data"`
	Paging struct {
		Next string `json:"next"`
	} `json:"paging"`
}

// IsAutoGenerated returns whether this is a template Meta generates itself for Direct Send messages, which channels
// that offer Direct Send leave out
func (t *MetaTemplate) IsAutoGenerated() bool {
	return t.Source == "AUTO_GENERATED"
}

type MetaComponent struct {
	Type    string        `json:"type"`
	Format  *string       `json:"format"`
	Text    string        `json:"text"`
	Buttons []*MetaButton `json:"buttons"`
}

type MetaButton struct {
	Type        string `json:"type"`
	Text        string `json:"text"`
	URL         string `json:"url"`
	PhoneNumber string `json:"phone_number"`
}

// ParseMetaTemplates parses templates in Meta's format. Templates which can't be parsed are returned as invalid rather
// than failing the rest.
func ParseMetaTemplates(raws []*MetaTemplate, defaultNamespace string) *templates.Fetched {
	fetched := &templates.Fetched{Translations: make([]*templates.Translation, 0, len(raws))}

	for _, raw := range raws {
		tr, err := ParseMetaTemplate(raw, defaultNamespace)
		if err != nil {
			fetched.Invalid = append(fetched.Invalid, err.(*templates.InvalidTemplateError))
		} else if tr != nil {
			fetched.Translations = append(fetched.Translations, tr)
		}
	}

	return fetched
}

// ParseMetaTemplate parses a template in Meta's format, returning nil if it has a status we don't store. Channels
// that don't include a namespace on each template provide a default one.
// A template which can't be parsed is returned as a *templates.InvalidTemplateError.
func ParseMetaTemplate(t *MetaTemplate, defaultNamespace string) (*templates.Translation, error) {
	status, ok := ParseStatus(t.Status)
	if !ok {
		return nil, nil
	}

	locale, err := ParseLanguage(t.Language)
	if err != nil {
		return nil, &templates.InvalidTemplateError{Name: t.Name, Err: err}
	}

	namespace := defaultNamespace
	if t.Namespace != nil {
		namespace = *t.Namespace
	}

	components, variables, supported := extractMetaComponents(t.Components)

	return &templates.Translation{
		Name:           t.Name,
		Locale:         locale,
		ExternalLocale: t.Language,
		ExternalID:     string(t.ID),
		Namespace:      namespace,
		Status:         status,
		Components:     components,
		Variables:      variables,
		IsSupported:    supported,
	}, nil
}

func extractMetaComponents(raw []*MetaComponent) ([]*templates.Component, []*templates.Variable, bool) {
	components := make([]*templates.Component, 0, len(raw))
	variables := make([]*templates.Variable, 0)
	supported := len(raw) > 0 // templates can come back without components

	addVariables := func(names []string, typ string) map[string]int {
		m := make(map[string]int, len(names))
		for _, name := range names {
			variables = append(variables, &templates.Variable{Type: typ})
			m[name] = len(variables) - 1
		}
		return m
	}

	// components can come in any order, but we always order them header, body, footer, buttons
	byType := make(map[string]*MetaComponent, len(raw))
	for _, c := range raw {
		typ := strings.ToUpper(c.Type)
		if typ != "HEADER" && typ != "BODY" && typ != "FOOTER" && typ != "BUTTONS" {
			supported = false
		}
		byType[typ] = c
	}

	if c := byType["HEADER"]; c != nil {
		format := "TEXT"
		if c.Format != nil {
			format = *c.Format
		}

		var typ string
		var vars map[string]int

		switch format {
		case "TEXT":
			typ = "header/text"
			vars = addVariables(extractVariables(metaVariableRegex, c.Text), "text")
		case "IMAGE", "VIDEO", "DOCUMENT":
			typ = "header/media"
			vars = addVariables([]string{"1"}, strings.ToLower(format))
		default:
			typ = "header/unknown"
			vars = map[string]int{}
			supported = false
		}

		components = append(components, &templates.Component{
			Name:      "header",
			Type:      typ,
			Content:   c.Text,
			Variables: vars,
		})
	}

	if c := byType["BODY"]; c != nil {
		vars := addVariables(extractVariables(metaVariableRegex, c.Text), "text")
		components = append(components, &templates.Component{
			Name:      "body",
			Type:      "body/text",
			Content:   c.Text,
			Variables: vars,
		})
	}

	if c := byType["FOOTER"]; c != nil {
		components = append(components, &templates.Component{
			Name:      "footer",
			Type:      "footer/text",
			Content:   c.Text,
			Variables: map[string]int{},
		})
	}

	if c := byType["BUTTONS"]; c != nil {
		for i, b := range c.Buttons {
			name := fmt.Sprintf("button.%d", i)
			display := b.Text

			switch strings.ToUpper(b.Type) {
			case "QUICK_REPLY":
				vars := addVariables(extractVariables(metaVariableRegex, b.Text), "text")
				components = append(components, &templates.Component{
					Name:      name,
					Type:      "button/quick_reply",
					Content:   b.Text,
					Variables: vars,
				})
			case "URL":
				vars := addVariables(extractVariables(metaVariableRegex, b.URL), "text")
				components = append(components, &templates.Component{
					Name:      name,
					Type:      "button/url",
					Content:   b.URL,
					Display:   &display,
					Variables: vars,
				})
			case "PHONE_NUMBER":
				components = append(components, &templates.Component{
					Name:      name,
					Type:      "button/phone_number",
					Content:   b.PhoneNumber,
					Display:   &display,
					Variables: map[string]int{},
				})
			default:
				supported = false
			}
		}
	}

	return components, variables, supported
}
