// The testdata cases are the raw templates from temba's template type tests, with what temba's own parsers make of
// them, so that a template synced by either is stored the same.
type testCase struct {
	Raw      json.RawMessage `json:"raw"`
	Expected json.RawMessage `json:"expected"`
}

func readCases(t *testing.T, path string) []*testCase {
	d, err := os.ReadFile(path)
	require.NoError(t, err)

	var tcs []*testCase
	jsonx.MustUnmarshal(d, &tcs)
	return tcs
}

// marshals a translation in the same shape as temba's expected values
func marshalTranslation(tr *templates.Translation) []byte {
	if tr == nil {
		return []byte(`null`)
	}

	var externalID *string
	if tr.ExternalID != "" {
		externalID = &tr.ExternalID
	}

	return jsonx.MustMarshal(map[string]any{
		"name":            tr.Name,
		"locale":          tr.Locale,
		"external_locale": tr.ExternalLocale,
		"external_id":     externalID,
		"namespace":       tr.Namespace,
		"status":          tr.Status,
		"components":      tr.Components,
		"variables":       tr.Variables,
		"is_supported":    tr.IsSupported,
	})
}

func TestParseMetaTemplate(t *testing.T) {
	for i, tc := range readCases(t, "testdata/meta.json") {
		raw := &formats.MetaTemplate{}
		jsonx.MustUnmarshal(tc.Raw, raw)

		tr, err := formats.ParseMetaTemplate(raw, "default_namespace")
		require.NoError(t, err, "%d: error parsing", i)
		assert.JSONEq(t, string(tc.Expected), string(marshalTranslation(tr)), "%d: translation mismatch", i)
	}

	_, err := formats.ParseMetaTemplate(&formats.MetaTemplate{Name: "hello", Language: "xx_US", Status: "APPROVED"}, "")
	assert.EqualError(t, err, "error parsing template hello: unrecognized language code: xx_US")

	assert.True(t, (&formats.MetaTemplate{Source: "AUTO_GENERATED"}).IsAutoGenerated())
	assert.False(t, (&formats.MetaTemplate{}).IsAutoGenerated())
}

func TestParseTwilioContent(t *testing.T) {
	for i, tc := range readCases(t, "testdata/twilio.json") {
		raw := &formats.TwilioContent{}
		jsonx.MustUnmarshal(tc.Raw, raw)

		tr, err := formats.ParseTwilioContent(raw, templates.StatusApproved)
		require.NoError(t, err, "%d: error parsing", i)
		assert.JSONEq(t, string(tc.Expected), string(marshalTranslation(tr)), "%d: translation mismatch", i)
	}

	// temba fails on a content type that isn't an object
	_, err := formats.ParseTwilioContent(&formats.TwilioContent{FriendlyName: "hello", Language: "en", Types: []byte(`{"twilio/text": "Hi"}`)}, templates.StatusApproved)
	assert.EqualError(t, err, "error parsing template hello: content type twilio/text isn't an object")
}

func TestParseStatus(t *testing.T) {
	s, ok := formats.ParseStatus("approved")
	assert.True(t, ok)
	assert.Equal(t, templates.StatusApproved, s)

	s, ok = formats.ParseStatus("IN_APPEAL")
	assert.True(t, ok)
	assert.Equal(t, templates.StatusInAppeal, s)

	_, ok = formats.ParseStatus("PENDING_DELETION")
	assert.False(t, ok)
}

func TestParseLanguage(t *testing.T) {
	// what temba makes of each language WhatsApp supports
	d, err := os.ReadFile("testdata/languages.json")
	require.NoError(t, err)

	var expected map[string]i18n.Locale
	jsonx.MustUnmarshal(d, &expected)

	for code, locale := range expected {
		actual, err := formats.ParseLanguage(code)
		assert.NoError(t, err, "error parsing %s", code)
		assert.Equal(t, locale, actual, "locale mismatch for %s", code)
	}
}
