// Package dialog360 syncs the templates of 360dialog WhatsApp channels.
package dialog360

import (
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"slices"
	"strings"

	"github.com/nyaruka/mailroom/v26/core/models"
	"github.com/nyaruka/mailroom/v26/core/templates"
	"github.com/nyaruka/mailroom/v26/core/templates/formats"
	"github.com/nyaruka/mailroom/v26/runtime"
)

const (
	channelType = models.ChannelType("D3C")

	configBaseURL   = "base_url"
	configAuthToken = "auth_token"
	configNamespace = "fb_namespace"
)

func init() {
	templates.RegisterService(channelType, New)
}

type service struct {
	httpClient *http.Client
	baseURL    string
	authToken  string
	namespace  string
}

// New creates a new templates service for the given 360dialog channel
func New(cfg *runtime.Config, httpClient *http.Client, channel *models.Channel) (templates.Service, error) {
	baseURL := channel.Config().GetString(configBaseURL, "")
	authToken := channel.Config().GetString(configAuthToken, "")
	if baseURL == "" || authToken == "" {
		return nil, fmt.Errorf("missing %s or %s in channel config", configBaseURL, configAuthToken)
	}

	return &service{
		httpClient: httpClient,
		baseURL:    strings.TrimSuffix(baseURL, "/"),
		authToken:  authToken,
		namespace:  channel.Config().GetString(configNamespace, ""),
	}, nil
}

func (s *service) FetchTemplates(ctx context.Context, clog *models.ChannelLog) (*templates.Fetched, error) {
	headers := map[string]string{"D360-API-KEY": s.authToken}
	body, err := templates.Get(ctx, s.httpClient, clog, s.baseURL+"/v1/configs/templates", headers)
	if err != nil {
		return nil, err
	}

	var page struct {
		Templates []*formats.MetaTemplate `json:"waba_templates"`
	}
	if err := json.Unmarshal(body, &page); err != nil {
		return nil, fmt.Errorf("error unmarshaling templates: %w", err)
	}

	raws := slices.DeleteFunc(page.Templates, (*formats.MetaTemplate).IsAutoGenerated)

	return formats.ParseMetaTemplates(raws, s.namespace), nil
}

func (s *service) RedactValues(*models.Channel) []string {
	return []string{s.authToken}
}
