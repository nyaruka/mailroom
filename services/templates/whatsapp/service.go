// Package whatsapp syncs the templates of WhatsApp Cloud API channels from Meta's Graph API.
package whatsapp

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"net/url"
	"slices"

	"github.com/nyaruka/mailroom/v26/core/models"
	"github.com/nyaruka/mailroom/v26/core/templates"
	"github.com/nyaruka/mailroom/v26/core/templates/formats"
	"github.com/nyaruka/mailroom/v26/runtime"
)

const (
	channelType = models.ChannelType("WAC")

	configWABAID    = "wa_waba_id"
	configNamespace = "fb_namespace"
)

// BaseURL is the Graph API, a variable so tests can change it
var BaseURL = "https://graph.facebook.com/v25.0"

func init() {
	templates.RegisterService(channelType, New)
}

type service struct {
	httpClient *http.Client
	token      string
	wabaID     string
	namespace  string
}

// New creates a new templates service for the given WhatsApp Cloud API channel
func New(cfg *runtime.Config, httpClient *http.Client, channel *models.Channel) (templates.Service, error) {
	wabaID := channel.Config().GetString(configWABAID, "")
	if wabaID == "" {
		return nil, fmt.Errorf("missing %s in channel config", configWABAID)
	}
	if cfg.WhatsappAdminSystemUserToken == "" {
		return nil, errors.New("missing WhatsApp admin system user token")
	}

	return &service{
		httpClient: httpClient,
		token:      cfg.WhatsappAdminSystemUserToken,
		wabaID:     wabaID,
		namespace:  channel.Config().GetString(configNamespace, ""),
	}, nil
}

func (s *service) FetchTemplates(ctx context.Context, clog *models.ChannelLog) (*templates.Fetched, error) {
	headers := map[string]string{"Authorization": "Bearer " + s.token}
	next := fmt.Sprintf("%s/%s/message_templates?limit=255", BaseURL, url.PathEscape(s.wabaID))
	raws := make([]*formats.MetaTemplate, 0)

	base, _ := url.Parse(BaseURL)

	for next != "" {
		if err := templates.CheckHost(next, base.Host); err != nil {
			return nil, err
		}

		body, err := templates.Get(ctx, s.httpClient, clog, next, headers)
		if err != nil {
			return nil, err
		}

		page := &formats.MetaPage{}
		if err := json.Unmarshal(body, page); err != nil {
			return nil, fmt.Errorf("error unmarshaling templates: %w", err)
		}

		raws = append(raws, page.Data...)
		next = page.Paging.Next
	}

	raws = slices.DeleteFunc(raws, (*formats.MetaTemplate).IsAutoGenerated)

	return formats.ParseMetaTemplates(raws, s.namespace), nil
}

func (s *service) RedactValues(*models.Channel) []string {
	return []string{s.token}
}
